export function getTranslation(source, language) {
  const normalized = String(source).replace(/\s+/g, ' ').trim();
  const entry = uiTranslations[normalized];
  if (!entry) return source;
  if (language === 'en') return Array.isArray(entry) ? entry[0] : entry;
  if (language === 'ar') return Array.isArray(entry) ? entry[1] : entry;
  return source;
}
